import type { FastifyInstance } from "fastify";
import { z } from "zod";
import { prisma } from "../../lib/prisma.js";
import { Errors } from "../../lib/errors.js";
import { parseBody } from "../../lib/validate.js";
import { centralAdminOnly } from "../../lib/centralAdmin.js";
import { serializeSummary } from "../../notifications/dailySummary.js";
import { parseSummaryApiId } from "../../notifications/schedule.js";

const READ = { rateLimit: { max: 120, timeWindow: "1 minute" } };
const listQuery = z.object({ limit: z.coerce.number().int().min(1).max(60).default(14) });

/** Stored daily summaries (D-22). Read-only: they are generated by the scheduler, never edited. */
export default async function adminDailySummariesRoutes(fastify: FastifyInstance) {
  fastify.addHook("preHandler", fastify.requireRole("ADMIN"));
  fastify.addHook("preHandler", centralAdminOnly("view daily summaries"));

  fastify.get("/", { config: READ }, async (request) => {
    const { limit } = parseBody(listQuery, request.query);
    const rows = await prisma.dailySummary.findMany({ orderBy: [{ businessDate: "desc" }, { kind: "asc" }], take: limit });
    return { items: rows.map(serializeSummary) };
  });

  // GET /api/admin/daily-summaries/:id   — "YYYY-MM-DD" (main) or "YYYY-MM-DD-supplementary"
  fastify.get("/:id", { config: READ }, async (request) => {
    const { id } = request.params as { id: string };
    const parsed = parseSummaryApiId(id);
    if (!parsed) throw Errors.notFound("Daily summary not found.", "SUMMARY_NOT_FOUND");
    const row = await prisma.dailySummary.findUnique({ where: { businessDate_kind: { businessDate: parsed.date, kind: parsed.kind } } });
    if (!row) throw Errors.notFound("Daily summary not found.", "SUMMARY_NOT_FOUND");
    return serializeSummary(row);
  });
}
